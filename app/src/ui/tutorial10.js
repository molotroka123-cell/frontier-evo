// ---------------------------------------------------------------- прогресс ---
// Сводка для HUD. done — сколько шагов закрыто фактом; current — id первого
// незакрытого шага «по делу» (пропущенные по skipIf прозрачны) либо null,
// когда всё пройдено. Чистая функция: только чтение sim.
export function tutorialProgress(sim) {
  const total = TUTORIAL10.length;
  let done = 0;
  let current = null;
  for (const st of TUTORIAL10) {
    let skipped = false;
    if (st.skipIf) { try { skipped = !!st.skipIf(sim); } catch { skipped = true; } }
    if (!skipped) {
      let passed = false;
      try { passed = !!st.check(sim); } catch { passed = false; }
      if (passed) done++;
      else if (!current) current = st.id;
    }
  }
  return { done, total, current };
}
