// core/systems/banner.js — ЗНАМЕНОСЕЦ: знамя как боевая единица.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. У знамени уже есть «аура духа» в front.js (мораль
// соседям в радиусе), но боевой силе, гибели знамени в конкретном бою и
// трофею на карте там взяться неоткуда: front.js видит бой только по снимку
// «до/после» и в формулу удара не вмешивается. Здесь знамя доведено до конца:
//   · прибавка силы дерущемуся отряду — с НАСЫЩЕНИЕМ по числу знамён;
//   · гибель знаменосца — РАЗОВЫЙ шок духа этой армии (флаг снимается, поэтому
//     накопиться за тики он не может физически);
//   · победа под живым знаменем — трофейная точка на карте через worldsites.js
//     и запись в хронику как СОБЫТИЕ, а не состояние.
//
// ПРАВИЛА ЧИСТОТЫ. Ни одного броска случайности: множитель и подсчёт поддержки
// детерминированы, трофей ставится без кубика. Мир модулю не принадлежит —
// WorldSites передаётся снаружи (ctx.sites в army.js), поэтому связка
// army ↔ banner ↔ worldsites остаётся инъекцией зависимостей и тестируется
// в отрыве от симуляции.

// ---------------- Константы модели (экспортируются: на них опирается тест) ----------------

// Потолок прибавки боевой силы от знамён (+15%). Выбран по калибровке army.js:
// контра даёт ~+10% силы, высота ~+15% стрелкам — знамя того же порядка, чтобы
// оставалось «заметным, но не решающим» на фоне состава и рельефа.
export const BANNER_POWER_CAP = 0.15;

// Сколько знамён дают половину потолка. Формула насыщения 1 + CAP·k/(k+HALF):
// первое знамя даёт CAP/3 ≈ +5%, второе добавляет уже +2.5%, десятое — меньше
// процента. Именно убывающая полезность мешает стратегии «слепить комок из
// пяти знаменосцев»: выгоднее держать знамёна в разных отрядах, чем дублировать.
export const BANNER_HALF = 2;

// Радиус взаимодействия знамён с дерущимся отрядом. Сопоставим с глубиной
// боевого порядка: дальше знамени отряд его просто не видит за стеной строя.
export const BANNER_COORD_RADIUS = 8;

// Разовый шок духа при потере знамени (сверх −35 за само бегство в applyBattle).
// Меньше потери боя, но ощутимее аурной мелочи: знамя — не флажок, а клятва.
export const BEARER_FALL_SHOCK = 20;

// Сколько клеток вокруг трофея открывается на карте. Знамя на месте победы —
// ориентир для игрока: его видно издалека, иначе механика нема.
export const TROPHY_REVEAL = 3;

// Цвет трофея по умолчанию — золото игрока, тот же, что выбран для отрядов
// 'player' в рендере (см. INTEGRATION army.js п.8).
export const PLAYER_COLOR = '#c8a24a';

// ---------------- Формула силы ----------------

// Множитель боевой силы стороны от k поддерживающих знамён. Насыщение встроено
// в саму формулу: предел 1 + CAP недостижим ни при каком k, поэтому отдельный
// кламп не нужен — потолок нельзя обойти большим числом знамён.
// Дробные k округляются вниз: половина знаменосца не воодушевляет.
export function bannerPowerMult(k) {
  const n = Math.max(0, Math.floor(k || 0));
  if (n <= 0) return 1;
  return 1 + BANNER_POWER_CAP * n / (n + BANNER_HALF);
}

// ---------------- Знамя на отряде ----------------
// Флаг живёт на самом отряде (sq.banner), а не в реестре со стороны: бой в
// resolveBattle получает именно отряды, а serializeArmy кладёт их в JSON целиком.
// Так знамя переживает сейв без дополнительного слоя состояния.

export function hasBearer(sq) { return !!(sq && sq.banner); }

export function assignBearer(sq) {
  if (!sq || sq.banner) return false;
  sq.banner = true;
  return true;
}

export function revokeBearer(sq) {
  if (!sq || !sq.banner) return false;
  sq.banner = false;
  return true;
}

// Живость отряда — локальная копия проверки из army.js. Дубликат намеренный:
// импорт army.js сюда замкнул бы цикл army → banner → army, а три строки
// дешевле цикла.
function _alive(sq) {
  if (!sq || sq.dead) return false;
  for (const v of Object.values(sq.units || {})) if (v > 0) return true;
  for (const v of Object.values(sq.engines || {})) if (v > 0) return true;
  return false;
}

// Сколько знамён поддерживает дерущийся отряд: он сам плюс свои живые
// знаменосцы в радиусе взаимодействия. Чужие знамёна не воодушевляют, мёртвые
// не считаются — иначе погибший знаменосец продолжал бы усиливать армию.
// friends — уже отфильтрованные по стороне соседи (их готовит army.js),
// поэтому здесь только радиус и флаг.
export function bannerSupport(sq, friends, radius = BANNER_COORD_RADIUS) {
  let k = 0;
  if (_alive(sq) && hasBearer(sq)) k++;
  for (const f of friends || []) {
    if (!f || f === sq) continue;
    if (!_alive(f) || !hasBearer(f)) continue;
    if (sq.side && f.side !== sq.side) continue;
    if (Math.hypot(f.x - sq.x, f.y - sq.y) > radius) continue;
    k++;
  }
  return k;
}

// ---------------- Трофей через worldsites.js ----------------

// Ставит «Трофейное знамя» на карту победы. sites — экземпляр WorldSites ядра:
// модуль не импортирует его сам, потому что владелец карты — симуляция, а не
// боевая математика. Нет карты (тесты, отряды без привязки) — тихий отказ,
// бой не должен ломаться от отсутствия декорации.
export function plantTrophy(sites, x, y, opts = {}) {
  if (!sites || typeof sites.plantBanner !== 'function') {
    return { ok: false, reason: 'Карта точек не подключена' };
  }
  return sites.plantBanner(x, y, opts);
}
