// render/water_fx.js — верхний слой воды: бегущие блики-спеклы по зеркалу,
// пульсирующая пена у кромки суши и мерные вспышки течения на реках.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. water.js богат, но его анимация живёт внутри
// выпечки чанка и включается только с richWater. Здесь наоборот: ноль
// выпечки, ноль канвасов-буферов — чистая математика фаз плюс дешёвые
// примитивы прямо в кадре, поэтому слой совместим и с плоской водой eco
// ветки terrain.drawWater (хотя на самом eco он всё равно молчит — см.
// КАЧЕСТВО), и с полной водой water.js, добавляя ей мелкую жизнь.
//
// ГРАНИЦЫ. Модуль читает world.tiles через собственный wet() и НИЧЕГО
// не меняет: ни в симуляции, ни в других слоях рендера. Свой wet() нужен
// потому, что core.isWater за границей карты отвечает «вода» (tileAt
// возвращает DEEP), и кромка карты получала бы пену в пустоту. Импорт не
// имеет побочных эффектов — ни одного обращения к document до первого кадра.
//
// СЛУЧАЙНОСТЬ. Ни Math.random, ни rng ядра (каждый вызов сдвинул бы
// состояние симуляции — сейв бы поплыл). Все фазы — чистые функции от
// (сид мира, координаты клетки, время), дрожь кадра — hash4 от номера
// кадра. Хэш локальный, а не из atmosphere.js: этот слой обязан работать
// даже если соседний модуль ещё не подключён или сменит API. Одинаковые
// входы дают одинаковые позиции, что и проверяет тест.
//
// ТЕЧЕНИЕ БЕЗ ПОЛЯ СКОРОСТЕЙ. water.js строит направление русла структурным
// тензором поля расстояний — дорого повторять. Здесь русло опознаётся
// локально: клетка воды, у которой вода продолжается ровно по одной оси
// (вверх-вниз или влево-вправо), а поперёк суша, — это река; направление
// знака — наружу к краю карты, где в этой генерации лежит море. Та же
// эвристика знака, что в water._buildFlow, но за O(1) на клетку.
//
// ЗИМА. Модуль не отслеживает ледостав (freeze из water.js ему недоступен),
// поэтому в зимний сезон слой гаснет целиком: блики поверх льда читались
// бы как дырка в нём.
import { TILE } from '../core/data.js';

const TAU = Math.PI * 2;
const TILE_PX = 32;   // мировая единица «тайл→экран» при zoom=1, как в renderer.js

// Потолки кадра. Именно потолки: столько элементов слой не превысит ни при
// каком разрешении; пресет и площадь экрана только уменьшают плотность.
export const WATER_LIMITS = {
  specles: 260,   // бликов на зеркале
  foam: 200,      // сегментов пены вдоль кромок
  dashes: 160,    // вспышек течения
};

// Периоды фаз вынесены для тестов: циклы обязаны оставаться в этих рамках.
export const SPECLE_CYCLE_MIN = 2.2;
export const SPECLE_CYCLE_MAX = 4.0;
export const FOAM_PERIOD = 0.85;    // рад/с, синхронно с прибоем water._compose
export const FLOW_CYCLE = 1.6;

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

// ---------------------------------------------------------------------------
// Детерминированный шум [0..1) от четырёх целых. Локальная копия схемы
// palette.hash2/postfx.hashP с лавиной imul: четыре разных множителя не дают
// коррелировать сиду, координатам, соли свойства и номеру кадра между собой.
// ---------------------------------------------------------------------------
export function hash4(seed, x, y, salt) {
  let h = (seed | 0) ^ 0x9e3779b9;
  h = Math.imul(h ^ ((x | 0) + 0x7f4a7c15), 0x85ebca6b);
  h = Math.imul(h ^ ((y | 0) + 0x165667b1), 0xc2b2ae35);
  h = Math.imul(h ^ ((salt | 0) + 0x27d4eb2f), 0x27d4eb2f);
  h ^= h >>> 15;
  h = Math.imul(h, 0x2545f491);
  h ^= h >>> 13;
  return (h >>> 0) / 4294967296;
}

// ---------------------------------------------------------------------------
// СПЕКЛ. Одна клетка зеркала несёт один блик, который бежит по ней по
// диагонали и гаснет; фаза клетки — её личная, поэтому зеркало мерцает
// россыпью, а не шахматкой.
// Возвращает { u, v, a }: позиция внутри клетки [0..1] и яркость [0..1].
// Период функции равен личному циклу клетки (проверено тестом): фазы не
// накапливают ошибку и не «плывут» относительно друг друга.
// ---------------------------------------------------------------------------
export function speclePhase(seed, tx, ty, t) {
  const j = hash4(seed, tx, ty, 41);
  const cycle = SPECLE_CYCLE_MIN + j * (SPECLE_CYCLE_MAX - SPECLE_CYCLE_MIN);
  const k = ((t / cycle) + j) % 1;
  // Направление пробега слегка своё у каждой клетки: две разрешённые
  // диагонали, иначе вся вода ползёт в одну сторону как конвейер.
  const flip = j > 0.5 ? 1 : -1;
  return {
    u: 0.5 + flip * (k - 0.5) * 0.86,
    v: 0.5 + (k - 0.5) * 0.62,
    // sin^2 даёт мягкий ноль на концах пробега: блик не мигает резко.
    a: Math.pow(Math.sin(Math.PI * k), 2) * (0.35 + 0.45 * j),
  };
}

// ---------------------------------------------------------------------------
// ПЕНА У КРОМКИ. Пульс ширины: глобальная волна прибоя (тот же период, что
// у двух фаз пены water.js, чтобы слои дышали вместе) плюс личная фаза
// клетки, разбивающая прямую кайму на живые язычки.
// Возвращает { w, k }: множитель ширины [FOAM_W_MIN..FOAM_W_MAX] и фаза [0..1].
// ---------------------------------------------------------------------------
export const FOAM_W_MIN = 0.55;
export const FOAM_W_MAX = 1.05;

// FOAM_PERIOD — угловая частота в рад/с и совпадает с частотой перекрёстного
// затухания прибоя water._compose (`Math.sin(this.time * 0.85)`), чтобы оба
// слоя пены дышали в такт, а не вразнобой.
export function foamEdge(seed, wx, wy, t) {
  const j = hash4(seed, wx, wy, 53);
  const k = 0.5 + 0.5 * Math.sin(t * FOAM_PERIOD + j * TAU);
  return { w: FOAM_W_MIN + (FOAM_W_MAX - FOAM_W_MIN) * k, k };
}

// ---------------------------------------------------------------------------
// ОСЬ РУСЛА. По четырём соседям: если вода продолжается только по одной оси,
// это русло. Возвращает единичную ось {ax, ay} или null (озеро/морской узел).
// Диагонали сознательно не различаются: для мерцания достаточно оси.
// ---------------------------------------------------------------------------
export function riverAxis(wetUp, wetDown, wetLeft, wetRight) {
  const v = (wetUp ? 1 : 0) + (wetDown ? 1 : 0);
  const h = (wetLeft ? 1 : 0) + (wetRight ? 1 : 0);
  if (v > 0 && h === 0) return { ax: 0, ay: 1 };   // вертикальное русло
  if (h > 0 && v === 0) return { ax: 1, ay: 0 };   // горизонтальное русло
  return null;
}

// ---------------------------------------------------------------------------
// ВСПЫШКА ТЕЧЕНИЯ. Светлая чёрточка скользит по клетке вдоль оси русла;
// знак направления — наружу к ближнему краю карты (море в этой генерации
// лежит по краям — та же эвристика знака, что у water._buildFlow).
// strength [0..1] задаёт длину и яркость: у истока река тише морского рукава.
// Возвращает { cx, cy, len, a } в тайлах: центр чёрточки всегда внутри
// своей клетки (|смещение| <= 0.575 < 0.5+запас), соседние клетки не спорят.
// ---------------------------------------------------------------------------
export function riverDash(seed, x, y, W, H, t, ax, ay, strength) {
  const s = clamp01(strength);
  const j = hash4(seed, x, y, 67);
  const k = ((t / FLOW_CYCLE) + j) % 1;
  // Знак течения: наружу от центра карты. Горизонтальное русло сравнивается
  // с половиной ширины W, вертикальное — с половиной высоты H; вызывающий
  // передаёт обе размерности, потому что знак по Y без H не вычислить.
  const dirX = ax !== 0 ? (x * 2 < W ? -1 : 1) : 0;
  const dirY = ay !== 0 ? (y * 2 < H ? -1 : 1) : 0;
  // Чёрточка проходит клетку насквозь за один цикл: travel ∈ [-0.575..0.575].
  const travel = (k - 0.5) * 1.15;
  return {
    cx: x + 0.5 + ax * dirX * travel,
    cy: y + 0.5 + ay * dirY * travel,
    len: 0.16 + 0.26 * s,                                   // длина, тайлы
    a: Math.sin(Math.PI * k) * (0.30 + 0.34 * s),           // ноль на концах цикла
  };
}

// ===========================================================================
// WaterFx — обход видимых клеток и отрисовка посчитанных фаз.
// ===========================================================================
export class WaterFx {
  constructor(quality) {
    this.q = quality || null;
    this.time = 0;
  }

  setQuality(q) { this.q = q || null; }

  // Вызов один раз за кадр после слоёв воды и ДО зданий. Безопасен при любых
  // неполных данных: нет сима/мира/канваса или качество выключено — ранний
  // выход после обновления часов.
  draw(sim, ctx, ox, oy, z, cw, ch, dt, L, q) {
    dt = Math.min(0.05, Math.max(0, dt || 0));
    this.time += dt;
    if (!ctx) return;   // канваса нет (headless/миникарта) — рисовать некуда
    if (!q || !(q.particles > 0) || q.id === 'eco') return;
    // Слой имеет смысл только там, где вода вообще анимирована.
    if (!q.water && !q.richWater) return;
    if (!sim || !sim.world || !sim.world.tiles ||
        !(sim.world.w > 0) || !(sim.world.h > 0)) return;
    const zoom = z / TILE_PX;
    // Отрицательный/нулевой z отсекается тем же гейтом: zoom не дотягивает.
    if (!(zoom >= ((q.lod && q.lod.waterMinZoom) || 0.45))) return;
    const world = sim.world;
    if (sim.seasonIdx === 3) return;                 // зимой вода встала льдом

    const seed = world.seed | 0;
    const t = this.time;
    const lightK = L ? clamp01(0.35 + 0.65 * L.mul) : 1;   // ночью блики тускнеют

    // Видимый прямоугольник в тайлах, зажатый картой.
    const tx0 = Math.max(0, Math.floor(-ox / z));
    const ty0 = Math.max(0, Math.floor(-oy / z));
    const tx1 = Math.min(world.w - 1, Math.ceil((cw - ox) / z));
    const ty1 = Math.min(world.h - 1, Math.ceil((ch - oy) / z));
    if (tx1 < tx0 || ty1 < ty0) return;

    // Плотность от пресета и площади экрана (эталон 1280×720, как в weather.js).
    // areaK зажат сверху: без клампа монитор 4К умножил бы потолок вдвое.
    const areaK = Math.min(1.7, Math.max(0.35, (cw * ch) / (1280 * 720)));
    const dens = q.particles * areaK;
    let nSpec = Math.min(WATER_LIMITS.specles, Math.round(WATER_LIMITS.specles * dens));
    let nFoam = Math.min(WATER_LIMITS.foam, Math.round(WATER_LIMITS.foam * dens));
    let nDash = Math.min(WATER_LIMITS.dashes, Math.round(WATER_LIMITS.dashes * dens));
    const frame = Math.round(t * 30);

    // Своя проверка «мокро»: isWater из core считает клетку за краем карты
    // водой (DEEP), и берег получил бы пену, смотрящую в пустоту.
    const wet = (x, y) =>
      x >= 0 && y >= 0 && x < world.w && y < world.h &&
      (world.tiles[y * world.w + x] === TILE.WATER || world.tiles[y * world.w + x] === TILE.DEEP);

    ctx.save();
    // --- спеклы: одна дуга на блик, стиль ставится один раз на весь проход ---
    ctx.fillStyle = '#eaf4ff';
    for (let y = ty0; y <= ty1 && nSpec > 0; y++) {
      for (let x = tx0; x <= tx1 && nSpec > 0; x++) {
        if (!wet(x, y)) continue;
        // Не каждая клетка несёт блик одновременно: личный порог клетки
        // прореживает россыпь без общего счётчика фаз.
        if (hash4(seed, x, y, 43) > 0.72) continue;
        const sp = speclePhase(seed, x, y, t);
        // Дрожь позиции от номера кадра: зеркало живёт, хотя фаза детерминирована.
        const jit = (hash4(seed, x, y, frame) - 0.5) * 0.06;
        const px = ox + (x + sp.u) * z, py = oy + (y + sp.v + jit) * z;
        if (px < -2 || py < -2 || px > cw + 2 || py > ch + 2) continue;
        const r = Math.max(0.7, z * 0.045);
        ctx.globalAlpha = clamp01(sp.a) * lightK;
        ctx.beginPath(); ctx.arc(px, py, r, 0, TAU); ctx.fill();
        nSpec--;
      }
    }

    // --- пена у кромок и вспышки течения -------------------------------------
    ctx.fillStyle = '#f2f8ff';     // один раз на проход: цвет общий у всей пены
    ctx.strokeStyle = '#dceeff';
    ctx.lineCap = 'round';
    for (let y = ty0; y <= ty1; y++) {
      for (let x = tx0; x <= tx1; x++) {
        if (!wet(x, y)) continue;
        const up = wet(x, y - 1), down = wet(x, y + 1);
        const left = wet(x - 1, y), right = wet(x + 1, y);

        if (nFoam > 0) {
          const fe = foamEdge(seed, x, y, t);
          const fw = fe.w * z * 0.14;
          ctx.globalAlpha = clamp01(0.22 + 0.20 * fe.k) * lightK;
          // Полоска пены кладётся ТОЛЬКО вдоль тех граней, за которыми суша:
          // у мыса пена обнимает его с трёх сторон, у открытой воды её нет.
          if (!up && y > 0 && nFoam > 0) {           // суша сверху
            ctx.fillRect(ox + x * z, oy + y * z, z, fw); nFoam--;
          }
          if (!down && y < world.h - 1 && nFoam > 0) {
            ctx.fillRect(ox + x * z, oy + (y + 1) * z - fw, z, fw); nFoam--;
          }
          if (!left && x > 0 && nFoam > 0) {
            ctx.fillRect(ox + x * z, oy + y * z, fw, z); nFoam--;
          }
          if (!right && x < world.w - 1 && nFoam > 0) {
            ctx.fillRect(ox + (x + 1) * z - fw, oy + y * z, fw, z); nFoam--;
          }
        }

        if (nDash > 0) {
          const axis = riverAxis(up, down, left, right);
          if (axis) {
            // Узкое русло: поперёк суша, вдоль вода. Сила вспышки — от того,
            // насколько длинно вода тянется вдоль оси (у истока короче).
            const along = axis.ax !== 0 ? (left + right) : (up + down);
            const d = riverDash(seed, x, y, world.w, world.h, t, axis.ax, axis.ay, 0.4 + 0.3 * along);
            const px = ox + d.cx * z, py = oy + d.cy * z;
            const lx = axis.ax * d.len * z, ly = axis.ay * d.len * z;
            if (px > -8 && py > -8 && px < cw + 8 && py < ch + 8) {
              ctx.globalAlpha = clamp01(d.a) * lightK;
              ctx.lineWidth = Math.max(0.8, z * 0.07);
              ctx.beginPath();
              ctx.moveTo(px - lx, py - ly);
              ctx.lineTo(px + lx, py + ly);
              ctx.stroke();
              nDash--;
            }
          }
        }
      }
    }
    ctx.restore();
  }
}

